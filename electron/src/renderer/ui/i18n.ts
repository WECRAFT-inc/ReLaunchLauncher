const DICTS: Record<Lang, Record<string, string> | null> = { fr: null, en: EN };

export function t(fr: string, vars?: Record<string, string | number>): string {
  const d = DICTS[current];
  let s = (d && d[fr]) || fr;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
  return s;
}

/** Nombre de textes traduits pour une langue (diagnostic et tests). */
export function coverage(l: Lang): number {
  return l === "fr" ? Infinity : Object.keys(DICTS[l] ?? {}).length;
}
